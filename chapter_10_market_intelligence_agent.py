from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field
import sqlite3
import json
import time
import pathlib

# --- 1. Schemas ---

class CompetitorData(BaseModel):
    name: str
    price_usd: float
    rating: float
    monthly_sales_estimate: int

class MarketReportSchema(BaseModel):
    niche: str
    average_price_usd: float
    projected_monthly_revenue_usd: float
    recommended_strategy: str
    competitors_analyzed: List[CompetitorData]


# --- 2. Persistent Memory & State Logger ---

class CapstoneMemoryDB:
    def __init__(self, db_path: str = ":memory:"):
        self.conn = sqlite3.connect(db_path)
        with self.conn:
            self.conn.execute("""
                CREATE TABLE IF NOT EXISTS capstone_audit (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    agent_name TEXT,
                    step_name TEXT,
                    details TEXT,
                    created_at REAL
                )
            """)

    def log(self, agent: str, step: str, details: Dict[str, Any]):
        with self.conn:
            self.conn.execute("""
                INSERT INTO capstone_audit (agent_name, step_name, details, created_at)
                VALUES (?, ?, ?, ?)
            """, (agent, step, json.dumps(details), time.time()))

    def get_log_count(self) -> int:
        cursor = self.conn.cursor()
        cursor.execute("SELECT COUNT(*) FROM capstone_audit")
        return cursor.fetchone()[0]


# --- 3. Specialized Capstone Agents ---

class ResearchScoutAgent:
    """Agent 1: Harvests and validates competitor market metrics."""
    def gather_market_data(self, niche: str) -> List[CompetitorData]:
        # Simulated verified market data
        raw_records = [
            {"name": "Legacy Publisher Guide", "price_usd": 49.99, "rating": 4.5, "monthly_sales_estimate": 140},
            {"name": "Indie Bestseller Handbook", "price_usd": 6.99, "rating": 4.7, "monthly_sales_estimate": 850},
            {"name": "Practical Crash Course", "price_usd": 14.99, "rating": 4.8, "monthly_sales_estimate": 420}
        ]
        return [CompetitorData(**rec) for rec in raw_records]

class FinancialAnalystAgent:
    """Agent 2: Synthesizes pricing elasticity and revenue projections."""
    def analyze(self, competitors: List[CompetitorData]) -> Dict[str, float]:
        avg_price = sum(c.price_usd for c in competitors) / len(competitors)
        total_market_units = sum(c.monthly_sales_estimate for c in competitors)
        # Recommended sweet-spot pricing: $9.99 Kindle + $24.99 Paperback
        projected_units = 300 # conservative baseline
        blended_revenue = projected_units * 9.99 * 0.70 # 70% royalty
        return {
            "average_price": round(avg_price, 2),
            "total_market_units": total_market_units,
            "projected_monthly_revenue": round(blended_revenue, 2)
        }

class ExecutiveReportGenerator:
    """Agent 3: Compiles publication-ready Markdown executive report."""
    def compile_report(self, niche: str, competitors: List[CompetitorData], stats: Dict[str, float], output_path: pathlib.Path) -> str:
        rows = "\n".join([f"| {c.name} | ${c.price_usd} | {c.rating} ⭐ | {c.monthly_sales_estimate} units |" for c in competitors])
        
        report_content = f"""# 📈 Market Intelligence Executive Brief: {niche}
**Generated by:** Autonomous Multi-Agent Capstone Pipeline  
**Date:** {time.strftime('%Y-%m-%d %H:%M:%S')}

---

## 1. Competitor Benchmark Matrix

| Competitor Title | Price | Rating | Estimated Monthly Sales |
|---|---|---|---|
{rows}

---

## 2. Statistical Analysis & Financial Projections
* **Market Average Price:** ${stats['average_price']} USD
* **Category Monthly Sales Volume:** {stats['total_market_units']} units
* **Projected Monthly Author Net Royalty:** ${stats['projected_monthly_revenue']} USD

---

## 3. Recommended Go-To-Market Strategy
1. **Launch at $7.99 - $9.99:** Undercuts legacy traditional books ($49.99) while maintaining a 70% net royalty margin.
2. **Include Verified Source Code Repository:** Eliminate negative reviews regarding code formatting.
3. **Dual Publish on Amazon KDP & Gumroad:** Capture both search-driven Kindle readers and developers seeking direct PDF/code packages.
"""
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(report_content, encoding="utf-8")
        return report_content


# --- 4. Master Capstone Orchestrator ---

def run_capstone_pipeline():
    print("=" * 65)
    print("🌟 CHAPTER 10: AUTONOMOUS MARKET INTELLIGENCE CAPSTONE PIPELINE")
    print("=" * 65)

    db = CapstoneMemoryDB()
    scout = ResearchScoutAgent()
    analyst = FinancialAnalystAgent()
    generator = ExecutiveReportGenerator()

    niche = "Autonomous AI Agents with Python"
    print(f"\n[PHASE 1]: Research Scout harvesting market data for '{niche}'...")
    competitors = scout.gather_market_data(niche)
    db.log("ScoutAgent", "harvest_data", {"count": len(competitors)})
    print(f"  Captured {len(competitors)} validated competitor benchmarks.")

    print(f"\n[PHASE 2]: Financial Analyst computing pricing elasticity & unit economics...")
    stats = analyst.analyze(competitors)
    db.log("AnalystAgent", "compute_projections", stats)
    print(f"  Calculated Average Price: ${stats['average_price']}")
    print(f"  Calculated Projected Monthly Net Royalty: ${stats['projected_monthly_revenue']}")

    print(f"\n[PHASE 3]: Executive Report Generator compiling production deliverable...")
    output_file = pathlib.Path("./generated_reports/market_intelligence_brief.md")
    report = generator.compile_report(niche, competitors, stats, output_file)
    db.log("GeneratorAgent", "publish_report", {"file": str(output_file)})

    print(f"  ✅ Report published to: {output_file.resolve()}")
    print(f"  ✅ SQLite Audit Log recorded {db.get_log_count()} autonomous state transitions.")

    print("\n" + "=" * 65)
    print("📋 GENERATED REPORT PREVIEW:")
    print("=" * 65)
    print(report)

if __name__ == "__main__":
    run_capstone_pipeline()
